function width(s, scale, tracking) {
  scale = scale || 1;
  tracking = tracking == null ? 1 : tracking;
  return s.length * (5 * scale + tracking) - tracking;
}

/* Draw uppercase text. `put(x, y)` is called for every ink pixel. */
function draw(s, x, y, scale, put, tracking) {
  scale = scale || 1;
  tracking = tracking == null ? 1 : tracking;
  s = String(s).toUpperCase();
  var cx = x;
  for (var i = 0; i < s.length; i++) {
    var g = G[s[i]] || G['?'];
    for (var r = 0; r < 7; r++) {
      for (var c = 0; c < 5; c++) {
        if (g[r][c] !== '1') continue;
        for (var sy = 0; sy < scale; sy++) {
          for (var sx = 0; sx < scale; sx++) put(cx + c * scale + sx, y + r * scale + sy);
        }
      }
    }
    cx += 5 * scale + tracking;
  }
}

